import fs from "node:fs";
import path from "node:path";
import type { Metadata } from "next";
import { Caveat, Montserrat } from "next/font/google";
import Header from "@/components/Header";
import Footer from "@/components/Footer";
import { getCaseCardByRoute } from "@/lib/case-cards-db";
import { pageMetadata } from "@/lib/metadata";
import CaseStudyScripts from "./CaseStudyScripts";

// The case study pages also use Montserrat italic 400 and, on Contract Intelligence, Caveat 600, as the reference
// loads them. Same family names as the layout's fonts, so the pages' own font-family rules find them.
// Their classes only define a custom property, so they style nothing; they make Next include the @font-face rules.
const montserratItalic = Montserrat({
  subsets: ["latin"],
  weight: "400",
  style: "italic",
  display: "swap",
  preload: false,
  variable: "--font-montserrat-italic",
});
const caveat = Caveat({ subsets: ["latin"], weight: "600", display: "swap", preload: false, variable: "--font-caveat" });

type PageInfo = { key: string; slug: string; title: string; description: string | null; scripts: number; caveat: boolean };

const DIR = path.join(process.cwd(), "content", "case-studies");
const PAGES: PageInfo[] = JSON.parse(fs.readFileSync(path.join(DIR, "pages.json"), "utf8"));

function page(key: string) {
  const info = PAGES.find((p) => p.key === key);
  if (!info) throw new Error(`Unknown case study page ${key}`);
  return info;
}

/** The page's own title and description; most reference pages have no description, so their card summary. */
export async function caseStudyMetadata(key: string): Promise<Metadata> {
  const { title, description, slug } = page(key);
  const summary = description ? undefined : (await getCaseCardByRoute(slug))?.summary;
  return pageMetadata({ title, description: description ?? summary, path: slug });
}

/**
 * A full case study page from the reference (content/case-studies/<key>, generated by
 * docs/website-redesign/tools/generate-case-study-pages.mjs): its body inside the shared Header and Footer,
 * its styles scoped to `.cs-<key>`, and its scripts run once the page is mounted.
 */
export default function FullCaseStudy({ pageKey }: { pageKey: string }) {
  const info = page(pageKey);
  const read = (file: string) => fs.readFileSync(path.join(DIR, pageKey, file), "utf8");
  const scripts = Array.from({ length: info.scripts }, (_, i) => read(`script-${i + 1}.js`));
  const fonts = [montserratItalic.variable, info.caveat ? caveat.variable : ""].filter(Boolean).join(" ");
  return (
    <>
      <Header />
      <style dangerouslySetInnerHTML={{ __html: read("style.css") }} />
      {/* .cs-frame is the page's first box: Next.js scrolls a newly opened page to its first element with a box, and
          <main> has none (display: contents, site.css), so without the frame it scrolled to the footer. */}
      <div className="cs-frame">
        <main className={`cs-page cs-${pageKey} ${fonts}`} dangerouslySetInnerHTML={{ __html: read("body.html") }} />
        <Footer />
      </div>
      <CaseStudyScripts scripts={scripts} />
    </>
  );
}
