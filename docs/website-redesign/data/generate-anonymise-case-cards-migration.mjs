// Writes the migration that takes client names off the 50 rows of the CaseCard table (Ali, 20 Oct 2026).
// It compares every card as it was on uat before the change (commit BASE: case-cards.json and the reference listing)
// with the cards now, and updates only the fields that changed: title, summary, organisation, industry, search text,
// drawing and slug. Other fields (position, tags, published) are not touched.
// It was run once, on 20 Oct 2026. The migration may already be applied, so this script refuses to overwrite it.
// Run: node docs/website-redesign/data/generate-anonymise-case-cards-migration.mjs

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const NAME = "20261020200000_remove_client_names_from_case_cards";
const BASE = "201db96d3bc2400f50349cf68a4a11eeecac3042";
const root = new URL("../../../", import.meta.url);
const JSON_PATH = "docs/website-redesign/data/case-cards.json";
const LISTING_PATH = "docs/website-redesign/reference/case-studies.html";
const read = (p) => readFileSync(new URL(p, root), "utf8");
const old = (p) => execFileSync("git", ["show", `${BASE}:${p}`], { cwd: new URL(root), encoding: "utf8", maxBuffer: 1 << 26 });

const unescape = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");

// The 50 cards as the CaseCard table holds them (same fields as generate-case-cards-migration.mjs).
function cards(json, listing, routes) {
  const data = JSON.parse(json);
  const html = [...listing.matchAll(/(<a class="ccard pc"[\s\S]*?<\/a>)(?=\s*<a class="ccard|\s*<\/div>)/g)].map((m) => m[1]);
  if (html.length !== 50 || data.length !== 50) throw new Error(`expected 50 cards, got ${html.length} / ${data.length}`);
  return data.map((e, i) => {
    const meta = html[i].match(/<div class="meta"><b>(.*?)<\/b><span>(.*?)<\/span><\/div>/);
    const route = e.currentRoute ?? routes[e.n] ?? null;
    return {
      number: e.n,
      title: e.title,
      summary: e.summary,
      org: e.org,
      industry: unescape(meta[2]),
      searchText: unescape(html[i].match(/data-search="([^"]*)"/)[1]),
      slug: route ? route.replace(/^\/case-studies\//, "") : null,
      art: e.cardArtSvg,
    };
  });
}

const before = cards(old(JSON_PATH), old(LISTING_PATH), { "50": "/case-studies/flexagon-implementation-execution-portal" });
const after = cards(read(JSON_PATH), read(LISTING_PATH), { "50": "/case-studies/implementation-execution-portal" });

// Standard SQL string literals: a quote is doubled; backslashes are literal (standard_conforming_strings).
const q = (s) => (s === null ? "NULL" : "'" + String(s).replace(/'/g, "''") + "'");

const updates = [];
for (const a of after) {
  const b = before.find((c) => c.number === a.number);
  const set = Object.keys(a).filter((k) => k !== "number" && a[k] !== b[k]);
  if (!set.length) continue;
  updates.push(
    `-- card ${a.number}: ${set.join(", ")}\n` +
      `UPDATE "CaseCard" SET ${set.map((k) => `"${k}" = ${q(a[k])}`).join(", ")}, "updatedAt" = CURRENT_TIMESTAMP WHERE "number" = ${q(a.number)};`,
  );
}

const sql = `-- Take client names off the case cards (Ali, 20 Oct 2026): titles lose their client prefix, organisation labels
-- describe the client by type, and four slugs change (the old ones redirect, see next.config.ts).
-- Only the fields that changed are set (generated by
-- docs/website-redesign/data/generate-anonymise-case-cards-migration.mjs).
${updates.join("\n\n")}
`;

const dir = new URL(`prisma/migrations/${NAME}/`, root);
if (existsSync(new URL("migration.sql", dir))) throw new Error(`prisma/migrations/${NAME}/migration.sql exists: an applied migration must not change`);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL("migration.sql", dir), sql);
console.log(`wrote prisma/migrations/${NAME}/migration.sql (${updates.length} cards updated)`);
