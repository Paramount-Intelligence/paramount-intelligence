// Writes the migration that creates the CaseCard table and fills it with the 50 cards in lib/case-cards.ts
// (the data the site used before the cards moved into the database; data option B in PORT-PLAN.md, section 3).
// Rows that already exist (same card number) are left alone, so the migration never overwrites /admin edits.
// Run once when the migration is created: node docs/website-redesign/data/generate-case-cards-migration.mjs

import { mkdirSync, writeFileSync } from "node:fs";

const NAME = "20261020120000_add_case_cards";
const root = new URL("../../../", import.meta.url);
const { CASE_CARDS } = await import(new URL("lib/case-cards.ts", root));

// Standard SQL string literals: a quote is doubled; backslashes are literal (standard_conforming_strings).
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const arr = (a) => (a.length ? "ARRAY[" + a.map(q).join(", ") + "]::TEXT[]" : "ARRAY[]::TEXT[]");

const rows = CASE_CARDS.map((c, i) =>
  "(" +
  [
    q(`card_${c.n}`),
    q(c.n),
    i + 1,
    q(c.title),
    q(c.summary),
    q(c.org),
    q(c.industry),
    arr(c.tags),
    q(c.search),
    c.route ? q(c.route.replace(/^\/case-studies\//, "")) : "NULL",
    c.fullCaseStudy,
    c.workInProgress,
    q(c.art),
    "CURRENT_TIMESTAMP",
  ].join(", ") +
  ")",
);

const sql = `-- CreateTable
CREATE TABLE "CaseCard" (
    "id" TEXT NOT NULL,
    "number" TEXT NOT NULL,
    "position" INTEGER NOT NULL,
    "title" TEXT NOT NULL,
    "summary" TEXT NOT NULL,
    "org" TEXT NOT NULL,
    "industry" TEXT NOT NULL,
    "tags" TEXT[] DEFAULT ARRAY[]::TEXT[],
    "searchText" TEXT NOT NULL,
    "slug" TEXT,
    "fullCaseStudy" BOOLEAN NOT NULL DEFAULT false,
    "workInProgress" BOOLEAN NOT NULL DEFAULT false,
    "art" TEXT NOT NULL,
    "published" BOOLEAN NOT NULL DEFAULT true,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "CaseCard_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE UNIQUE INDEX "CaseCard_number_key" ON "CaseCard"("number");

-- CreateIndex
CREATE UNIQUE INDEX "CaseCard_slug_key" ON "CaseCard"("slug");

-- CreateIndex
CREATE INDEX "CaseCard_position_idx" ON "CaseCard"("position");

-- The 50 cards from lib/case-cards.ts, in display order (generated by
-- docs/website-redesign/data/generate-case-cards-migration.mjs).
INSERT INTO "CaseCard" ("id", "number", "position", "title", "summary", "org", "industry", "tags", "searchText", "slug", "fullCaseStudy", "workInProgress", "art", "updatedAt") VALUES
${rows.join(",\n")}
ON CONFLICT ("number") DO NOTHING;
`;

const dir = new URL(`prisma/migrations/${NAME}/`, root);
mkdirSync(dir, { recursive: true });
writeFileSync(new URL("migration.sql", dir), sql);
console.log(`wrote prisma/migrations/${NAME}/migration.sql (${CASE_CARDS.length} cards, ${sql.length} bytes)`);
